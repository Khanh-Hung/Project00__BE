namespace Domain.Enums;

public enum WorldGenre
{
    Custom = 0,             // Tùy biến hoàn toàn: Tự do sáng tạo quy luật thế giới không giới hạn
    MundaneSliceOfLife = 1, // Đời thường thực tế: Học đường, công sở, tình cảm đô thị (Không phép thuật, vật lý thực tế)
    HighFantasy = 2,        // Kỳ ảo / Tu Tiên / Ma Pháp: Có linh lực/ma thuật, không có thiết bị hiện đại
    CyberpunkSciFi = 3,     // Khoa học viễn tưởng / Cyberpunk: Công nghệ cao, AI, cấy ghép máy móc
    UrbanSupernatural = 4,  // Đô thị siêu nhiên: Thế giới hiện đại có ma cà rồng/dị năng/phù thủy ẩn giấu
    Historical = 5,         // Cổ trang / Lịch sử thuần túy: Không phép thuật, phong tục cổ điển
