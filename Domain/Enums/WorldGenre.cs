    Superhero = 8,          // Siêu anh hùng / Siêu ác nhân: Đô thị hiện đại có năng lực đặc biệt công khai
    EldritchHorror = 9,     // Kinh dị vũ trụ / Bí ẩn tâm linh: Quái vật cổ xưa, nỗi sợ tinh thần (Sanity)
    SpaceOpera = 10,        // Du hành vũ trụ / Đế chế liên sao: Hạm đội không gian, các hành tinh xa xôi
    IsekaiOtherworld = 11   // Xuyên không / Chuyển sinh: Nhân vật từ thế giới khác mang ký ức đến vùng đất mới
}
